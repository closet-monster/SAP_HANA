INSERT INTO SAP_HANA_PROJECTX_HDI_DB_1.DIM_DATE
SELECT
    TO_INT(TO_VARCHAR(GENERATED_PERIOD_START, 'YYYYMMDD')) AS DATE_ID,
    GENERATED_PERIOD_START AS "CAL_DATE",
    YEAR(GENERATED_PERIOD_START) AS "YEAR",
    TO_TINYINT(SUBSTRING(QUARTER(GENERATED_PERIOD_START), 7, 1)) AS "QUARTER",
    MONTH(GENERATED_PERIOD_START) AS "MONTH",
    WEEK(GENERATED_PERIOD_START) AS "WEEK",
    DAYOFMONTH(GENERATED_PERIOD_START) AS "DAY"
FROM SERIES_GENERATE_DATE('INTERVAL 1 DAY', '2024-01-01', '2026-10-01');
